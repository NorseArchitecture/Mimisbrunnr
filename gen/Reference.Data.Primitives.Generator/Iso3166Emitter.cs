using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Norse.Abstractions.Emit;

namespace Norse.Reference.Data.Primitives.Generator;

/// <summary>
/// Emits the generated <c>Norse.Reference.Iso3166Country</c> and <c>Iso3166</c> dataset — every ISO
/// 3166-1 country/area row precomputed with a deterministic RFC 9562 version 5 identifier chained
/// from the realm's hand-minted root namespace (spec §6). The namespace constants themselves are
/// emitted separately by <see cref="NamespacesEmitter"/>, into the dedicated
/// <c>Norse.Reference.Data.Namespaces</c> assembly.
/// </summary>
static class Iso3166Emitter
{
	internal const string Iso3166NamespaceName = "iso3166-1";

	/// <summary>Renders the full generated source text for one CSV pass.</summary>
	/// <param name="members">Sanitized, ISO-bearing, collision-free rows in CSV order.</param>
	/// <param name="rootUuid">
	/// The single hand-minted namespace GUID (<c>ReferenceNamespaces.Root</c>) every dataset namespace
	/// and identifier in this file chains from.
	/// </param>
	internal static string Emit(IReadOnlyList<CountryMember> members, string rootUuid)
	{
		var root = new Guid(rootUuid);
		var iso3166Namespace = Uuid5.Compute(root, Iso3166NamespaceName);
		var rows = members
			.Select(m => (Member: m, Id: Uuid5.Compute(iso3166Namespace, m.Value.ToString("D3", CultureInfo.InvariantCulture))))
			.ToList();

		StringBuilder sb = new();
		sb.AppendCSharp(
			$$"""
			// <auto-generated/>
			#nullable enable
			#pragma warning disable CS1591

			// FrozenDictionary's extension methods (ToFrozenDictionary) have no global:: qualified
			// call form -- this using is a deliberate, documented exception to the fully-qualified
			// style used everywhere else in this generated file, not a reversion.
			using System.Collections.Frozen;

			namespace Norse.Reference;

			/// <summary>
			/// One ISO 3166-1 country/area row, generated at compile time from the UNSD M49 raw CSV.
			/// <see cref="Id"/> is a precomputed RFC 9562 version 5 identifier, deterministically
			/// derived from the ISO 3166-1 dataset namespace (<c>ReferenceNamespaces.Iso3166</c>,
			/// published by Norse.Reference.Data.Namespaces) and the
			/// zero-padded 3-digit M49 numeric code — recomputing it at runtime via
			/// <c>Norse.Primitives.Identifiers.DeterministicGuid</c> always reproduces the same value
			/// (spec §6 drift guard).
			/// </summary>
			public sealed record Iso3166Country(IsoCountryCode Code, string Alpha2, string Alpha3, string Name, global::System.Guid Id);

			/// <summary>
			/// The full ISO 3166-1 country/area dataset, generated at compile time from the UNSD M49
			/// raw CSV.
			/// </summary>
			public static class Iso3166
			{
				/// <summary>Every ISO-bearing row, in CSV order.</summary>
				public static readonly global::System.Collections.Generic.IReadOnlyList<Iso3166Country> All =
				[
			{{Rows(rows)}}
				];

				/// <summary>Row lookup by <see cref="IsoCountryCode"/>.</summary>
				public static readonly global::System.Collections.Frozen.FrozenDictionary<IsoCountryCode, global::System.Guid> Ids =
					new global::System.Collections.Generic.Dictionary<IsoCountryCode, global::System.Guid>
					{
			{{IdsEntries(rows)}}
					}.ToFrozenDictionary();
			}

			#pragma warning restore CS1591
			""");
		return sb.ToString();
	}

	static string Rows(IReadOnlyList<(CountryMember Member, Guid Id)> rows) =>
		string.Join("\n", rows.Select(r =>
			$"\t\tnew(IsoCountryCode.{r.Member.Identifier}, \"{r.Member.Alpha2}\", \"{r.Member.Alpha3}\", {StringLiteral(r.Member.Name)}, new global::System.Guid(\"{r.Id}\")),"));

	static string IdsEntries(IReadOnlyList<(CountryMember Member, Guid Id)> rows) =>
		string.Join("\n", rows.Select(r =>
			$"\t\t\t[IsoCountryCode.{r.Member.Identifier}] = new global::System.Guid(\"{r.Id}\"),"));

	static string StringLiteral(string value) =>
		SymbolDisplay.FormatLiteral(value, quote: true);
}
