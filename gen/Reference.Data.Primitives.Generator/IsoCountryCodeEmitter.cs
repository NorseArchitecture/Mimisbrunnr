using System.Text;
using Norse.Abstractions.Emit;

namespace Norse.Reference.Data.Primitives.Generator;

/// <summary>
/// Emits the generated <c>Norse.Reference.IsoCountryCode</c> enum and its tri-form
/// (numeric M49 / ISO alpha-2 / ISO alpha-3) span-based parser, <c>IsoCountryCodes</c>.
/// </summary>
static class IsoCountryCodeEmitter
{
	/// <summary>Renders the full generated source text for one CSV pass.</summary>
	/// <param name="members">Sanitized, ISO-bearing, collision-free rows in CSV order.</param>
	internal static string Emit(IReadOnlyList<CountryMember> members)
	{
		StringBuilder sb = new();
		sb.AppendCSharp(
			$$"""
			// <auto-generated/>
			#nullable enable
			#pragma warning disable CS1591

			// FrozenDictionary's extension methods (ToFrozenDictionary, GetAlternateLookup) have no
			// global:: qualified call form -- this using is a deliberate, documented exception to the
			// fully-qualified style used everywhere else in this generated file, not a reversion.
			using System.Collections.Frozen;

			namespace Norse.Reference;

			/// <summary>
			/// ISO 3166-1 country/area identifiers, generated at compile time from the UN Statistics
			/// Division M49 standard country/area classification raw export. Member values are the
			/// M49 numeric code.
			/// </summary>
			public enum IsoCountryCode : ushort
			{
				/// <summary>No country or area selected.</summary>
				None = 0,

			{{EnumMembers(members)}}
			}

			/// <summary>
			/// Tri-form (numeric M49 / ISO alpha-2 / ISO alpha-3) span-based parser for
			/// <see cref="IsoCountryCode"/>, generated at compile time from the UNSD raw CSV.
			/// Culture-insensitive — no <see cref="global::System.IFormatProvider"/>.
			/// </summary>
			public static class IsoCountryCodes
			{
				const string ExpectedType = nameof(IsoCountryCode);

				static readonly global::System.Collections.Frozen.FrozenDictionary<string, IsoCountryCode>.AlternateLookup<global::System.ReadOnlySpan<char>> _byAlpha2 =
					new global::System.Collections.Generic.Dictionary<string, IsoCountryCode>(global::System.StringComparer.OrdinalIgnoreCase)
					{
			{{Alpha2Entries(members)}}
					}.ToFrozenDictionary(global::System.StringComparer.OrdinalIgnoreCase).GetAlternateLookup<global::System.ReadOnlySpan<char>>();

				static readonly global::System.Collections.Frozen.FrozenDictionary<string, IsoCountryCode>.AlternateLookup<global::System.ReadOnlySpan<char>> _byAlpha3 =
					new global::System.Collections.Generic.Dictionary<string, IsoCountryCode>(global::System.StringComparer.OrdinalIgnoreCase)
					{
			{{Alpha3Entries(members)}}
					}.ToFrozenDictionary(global::System.StringComparer.OrdinalIgnoreCase).GetAlternateLookup<global::System.ReadOnlySpan<char>>();

				static readonly global::System.Collections.Frozen.FrozenDictionary<ushort, IsoCountryCode> _byNumeric =
					new global::System.Collections.Generic.Dictionary<ushort, IsoCountryCode>
					{
			{{NumericEntries(members)}}
					}.ToFrozenDictionary();

				/// <summary>
				/// Parses required tri-form country text: an M49 numeric code (1-3 digits, unpadded),
				/// an ISO alpha-2 code, or an ISO alpha-3 code. Empty or whitespace input is a
				/// <see cref="global::Norse.Primitives.ParseFailure.Empty"/> failure; unrecognized
				/// input is <see cref="global::Norse.Primitives.ParseFailure.Malformed"/>.
				/// </summary>
				/// <param name="value">The raw scalar text.</param>
				/// <returns>The parse outcome — never throws on bad input.</returns>
				public static global::Norse.Primitives.Result<IsoCountryCode> Parse(global::System.ReadOnlySpan<char> value)
				{
					var trimmed = value.Trim();
					if (trimmed.IsEmpty)
						return new global::Norse.Primitives.Failure(global::Norse.Primitives.ParseFailure.Empty, string.Empty, ExpectedType);

					if (trimmed.Length is >= 1 and <= 3 &&
						ushort.TryParse(trimmed, global::System.Globalization.NumberStyles.None, global::System.Globalization.CultureInfo.InvariantCulture, out var numeric))
					{
						return _byNumeric.TryGetValue(numeric, out var byNumeric)
							? new global::Norse.Primitives.Success<IsoCountryCode>(byNumeric)
							: new global::Norse.Primitives.Failure(global::Norse.Primitives.ParseFailure.Malformed, trimmed, ExpectedType);
					}

					if (trimmed.Length == 2 && _byAlpha2.TryGetValue(trimmed, out var byAlpha2))
						return new global::Norse.Primitives.Success<IsoCountryCode>(byAlpha2);

					if (trimmed.Length == 3 && _byAlpha3.TryGetValue(trimmed, out var byAlpha3))
						return new global::Norse.Primitives.Success<IsoCountryCode>(byAlpha3);

					return new global::Norse.Primitives.Failure(global::Norse.Primitives.ParseFailure.Malformed, trimmed, ExpectedType);
				}

				/// <summary>
				/// Parses required tri-form country text from a string. A null value converts to the
				/// empty span. See <see cref="Parse(global::System.ReadOnlySpan{char})"/> for the full
				/// contract.
				/// </summary>
				/// <param name="value">The raw scalar text.</param>
				/// <returns>The parse outcome — never throws on bad input.</returns>
				public static global::Norse.Primitives.Result<IsoCountryCode> Parse(string? value) =>
					Parse(value.AsSpan());

				/// <summary>
				/// Attempts to parse tri-form country text without constructing a failed
				/// <see cref="global::Norse.Primitives.Result{T}"/>.
				/// </summary>
				/// <param name="value">The raw scalar text.</param>
				/// <param name="code">The parsed code when this method returns <see langword="true"/>; otherwise <see cref="IsoCountryCode.None"/>.</param>
				/// <returns><see langword="true"/> when <paramref name="value"/> parsed successfully.</returns>
				public static bool TryParse(global::System.ReadOnlySpan<char> value, out IsoCountryCode code)
				{
					if (Parse(value).TryGetValue(out global::Norse.Primitives.Success<IsoCountryCode> success))
					{
						code = success.Value;
						return true;
					}

					code = IsoCountryCode.None;
					return false;
				}
			}

			#pragma warning restore CS1591
			""");
		return sb.ToString();
	}

	static string EnumMembers(IReadOnlyList<CountryMember> members) =>
		string.Join("\n", members.Select(m =>
			$"\t/// <summary>{XmlEscape(m.Name)} ({m.Alpha2} / {m.Alpha3}).</summary>\n\t{m.Identifier} = {m.Value},"));

	static string Alpha2Entries(IReadOnlyList<CountryMember> members) =>
		string.Join("\n", members.Select(m => $"\t\t\t[\"{m.Alpha2}\"] = IsoCountryCode.{m.Identifier},"));

	static string Alpha3Entries(IReadOnlyList<CountryMember> members) =>
		string.Join("\n", members.Select(m => $"\t\t\t[\"{m.Alpha3}\"] = IsoCountryCode.{m.Identifier},"));

	static string NumericEntries(IReadOnlyList<CountryMember> members) =>
		string.Join("\n", members.Select(m => $"\t\t\t[{m.Value}] = IsoCountryCode.{m.Identifier},"));

	static string XmlEscape(string value) =>
		value.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}

/// <summary>One sanitized, ISO-bearing UNSD row ready for emission.</summary>
readonly struct CountryMember
{
	internal CountryMember(string identifier, ushort value, string name, string alpha2, string alpha3)
	{
		Identifier = identifier;
		Value = value;
		Name = name;
		Alpha2 = alpha2;
		Alpha3 = alpha3;
	}

	internal string Identifier { get; }

	internal ushort Value { get; }

	internal string Name { get; }

	internal string Alpha2 { get; }

	internal string Alpha3 { get; }
}
